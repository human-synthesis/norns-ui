#!/usr/bin/env bun
/**
 * Generate COMPONENTS.md — the prop reference for every component — from
 * the hand-rolled shims in src/types/*.d.ts. Run after adding or changing
 * a component:
 *
 *   bun run docs:components          # write COMPONENTS.md
 *   bun run docs:components --check  # exit 1 if COMPONENTS.md is stale (CI)
 *
 * Output per component: the import path (components/ or motion/) and the
 * shim verbatim minus its `import type` / `declare const` / `export default`
 * lines, so the reference is exactly the public prop surface.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'COMPONENTS.md');
const CHECK = process.argv.includes('--check');

const shims = readdirSync(join(ROOT, 'src', 'types'))
	.filter((f) => f.endsWith('.d.ts'))
	.map((f) => f.replace(/\.d\.ts$/, ''))
	.sort((a, b) => a.localeCompare(b));

function sourceDir(name) {
	if (existsSync(join(ROOT, 'src', 'components', `${name}.n`))) return 'components';
	if (existsSync(join(ROOT, 'src', 'motion', `${name}.n`))) return 'motion';
	return null;
}

function propsBlock(name) {
	const text = readFileSync(join(ROOT, 'src', 'types', `${name}.d.ts`), 'utf8');
	const lines = text.split('\n').filter((line) => {
		const t = line.trim();
		if (t.startsWith('import type') || t.startsWith('import {')) return false;
		if (t.startsWith('declare const')) return false;
		if (t.startsWith('export default')) return false;
		return true;
	});
	while (lines.length && !lines[0].trim()) lines.shift();
	while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
	return lines.join('\n');
}

const groups = { components: [], motion: [] };
for (const name of shims) {
	const dir = sourceDir(name);
	if (!dir) continue; // orphan shims are reported by check-shims.mjs
	groups[dir].push(name);
}

const out = [];
out.push('# norns-ui — component reference');
out.push('');
out.push('Generated by `bun run docs:components` from `src/types/*.d.ts`. Do not edit by hand.');
out.push('');
out.push(
	'Every component under **components/** is auto-imported by name in `.n` files when the consumer wires `presetUI()` into `nornsAutoImport` (`Btn(variant="primary") Save`). Components under **motion/** are opt-in: `import { Reveal } from \'@human-synthesis/norns-ui/motion\'`. Snippet props (`children`, `header`, `trigger`, …) are filled with `+snippet(\'name\')` blocks in Pug. Every component accepts `class` and merges it with `cn()`.'
);
out.push('');
out.push('Live usage of every component: `norns-demo/src/routes/examples/ui/+page.n`.');
out.push('');

for (const [dir, names] of Object.entries(groups)) {
	out.push(`## ${dir === 'components' ? 'Components' : 'Motion (opt-in)'}`);
	out.push('');
	out.push(names.map((n) => `[${n}](#${n.toLowerCase()})`).join(' · '));
	out.push('');
	for (const name of names) {
		out.push(`### ${name}`);
		out.push('');
		out.push(
			dir === 'components'
				? `\`@human-synthesis/norns-ui/components/${name}.n\``
				: `\`import { ${name} } from '@human-synthesis/norns-ui/motion'\``
		);
		out.push('');
		out.push('```ts');
		out.push(propsBlock(name));
		out.push('```');
		out.push('');
	}
}

const markdown = out.join('\n');

if (CHECK) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
	if (current !== markdown) {
		console.error('COMPONENTS.md is out of date — run `bun run docs:components`.');
		process.exit(1);
	}
	console.log('COMPONENTS.md is up to date.');
} else {
	writeFileSync(OUT, markdown);
	console.log(`Wrote ${OUT} (${groups.components.length} components, ${groups.motion.length} motion).`);
}
